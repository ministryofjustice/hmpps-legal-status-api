--- Create and populate the OFFENDER_IMPRISONMENT_STATUS table

CREATE TABLE OFFENDER_IMPRISONMENT_STATUS
(
    ID                  UUID                     NOT NULL PRIMARY KEY,
    PRISON_NUMBER       VARCHAR(10)              NOT NULL,
    PRISON_ID           VARCHAR(3)               NOT NULL,
    IMPRISONMENT_STATUS VARCHAR(50)              NOT NULL REFERENCES IMPRISONMENT_STATUS (IMPRISONMENT_STATUS),
    COMMENT             VARCHAR(240),
    SOURCE              VARCHAR(10)              NOT NULL,
    CREATED_AT          TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY          VARCHAR(50)              NOT NULL,
    UPDATED_AT          TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_BY          VARCHAR(50)              NOT NULL
);

CREATE INDEX OFFENDER_IMPRISONMENT_STATUS__PRISON_NUMBER__IDX ON OFFENDER_IMPRISONMENT_STATUS (PRISON_NUMBER);
CREATE INDEX OFFENDER_IMPRISONMENT_STATUS__PRISON_ID__IDX ON OFFENDER_IMPRISONMENT_STATUS (PRISON_ID);
CREATE INDEX OFFENDER_IMPRISONMENT_STATUS__UPDATED_AT__IDX ON OFFENDER_IMPRISONMENT_STATUS (UPDATED_AT);
